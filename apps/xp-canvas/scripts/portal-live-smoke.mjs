import assert from 'node:assert/strict'
import { randomBytes } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright-core'
import { verifyProfileControls, selectProfileSkin, verifyInlinePassEditor, verifyProfileRefinements } from './portal-controls-checks.mjs'

// Explicit arguments only. Creates one synthetic account and one private test
// canvas, then disables the account, revokes its grant and trashes that canvas.
const [baseURL, secretFile, snapshotFile, reportFile] = process.argv.slice(2)
if (!baseURL || !secretFile || !snapshotFile || !reportFile || new URL(baseURL).protocol !== 'https:') throw new Error('Usage: node scripts/portal-live-smoke.mjs <https-portal> <private-secrets.json> <captured-snapshot.json> <new-private-report.json>')
const stamp = randomBytes(5).toString('hex').toUpperCase()
const username = `QA${stamp}`, password = randomBytes(20).toString('base64url'), nextPassword = randomBytes(20).toString('base64url')
const { PORTAL_BOOTSTRAP_PASSWORD: teacherPassword } = JSON.parse(await readFile(secretFile, 'utf8'))
const captured = JSON.parse(await readFile(snapshotFile, 'utf8'))
const snapshot = { ...captured, documents: captured.documents.filter((d) => ['page', 'document'].includes(d.state.typeName)) }
const report = { startedAt: new Date().toISOString(), baseURL, username, studentId: null, boardId: null, checks: [], cleanup: {} }
await writeFile(reportFile, JSON.stringify(report, null, 2), { flag: 'wx', mode: 0o600 })
const saveReport = () => writeFile(reportFile, JSON.stringify(report, null, 2), { mode: 0o600 })
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const teacher = await browser.newContext({ baseURL }), student = await browser.newContext({ baseURL, viewport: { width: 1024, height: 768 }, reducedMotion: 'reduce' })
const errors = [], licenseErrors = []
for (const context of [teacher, student]) context.on('page', (page) => {
	page.on('pageerror', (error) => errors.push(error.message))
	page.on('console', (message) => { if (['error', 'warning'].includes(message.type()) && /licen[sc]e.*(?:invalid|expired|missing)|(?:invalid|expired|missing).*licen[sc]e/i.test(message.text())) licenseErrors.push('tldraw license warning') })
})
const expected = async (response, status) => { assert.equal(response.status(), status, `${new URL(response.url()).pathname}: ${(await response.text()).slice(0, 160)}`); return response }
try {
	await expected(await teacher.request.post('/api/portal/login', { data: { username: 'leo', password: teacherPassword } }), 200)
	await expected(await teacher.request.post('/api/portal/students', { data: { students: [{ username, name: 'Prueba temporal' }] } }), 201)
	const roster = await (await teacher.request.get('/api/portal/roster')).json()
	report.studentId = roster.students.find((s) => s.username === username).id
	await saveReport()
	const imported = await expected(await teacher.request.post('/api/boards/import', { data: { version: 1, name: `QA temporal ${stamp}`, snapshot } }), 201)
	report.boardId = (await imported.json()).id
	await saveReport()
	const page = await student.newPage()
	await page.goto('/')
	await page.getByLabel('Matrícula', { exact: true }).fill(username)
	await page.getByLabel('Contraseña', { exact: true }).fill(username)
	await page.getByRole('button', { name: 'Entrar', exact: true }).click()
	await page.getByRole('heading', { name: 'Elige tu contraseña' }).waitFor()
	await expected(await student.request.get('/api/library'), 403)
	await page.getByLabel('Nueva contraseña', { exact: true }).fill(password)
	await page.getByLabel('Repite la contraseña', { exact: true }).fill(password)
	await page.getByRole('button', { name: 'Guardar y continuar' }).click()
	await page.getByRole('button', { name: 'Comenzar', exact: true }).waitFor()
	await expected(await student.request.get('/api/library'), 403)
	report.checks.push('forced password and server-side welcome gate')
	await page.getByRole('button', { name: 'Comenzar', exact: true }).click()
	await page.getByRole('button', { name: 'Firma', exact: true }).click()
	const signature = page.getByLabel('Dibuja tu firma con el cursor o el dedo', { exact: true })
	for (const key of ['Space', 'ArrowRight', 'ArrowUp', 'ArrowRight', 'Space']) await signature.press(key)
	await page.getByRole('button', { name: 'Listo, guardar firma', exact: true }).click()
	await page.getByRole('button', { name: 'Continuar', exact: true }).click()
	await page.getByRole('button', { name: 'Continuar', exact: true }).click()
	await page.getByRole('button', { name: 'Rasgar el sobre hacia la izquierda', exact: true }).press('Enter')
	await page.getByRole('button', { name: 'Continuar', exact: true }).click()
	await page.getByRole('button', { name: 'Descargar imagen', exact: true }).waitFor()
	await page.getByRole('button', { name: 'Continuar', exact: true }).click()
	await page.getByRole('button', { name: 'Insertar pase y entrar a mis clases', exact: true }).press('Enter')
	await page.getByTestId('student-boards').waitFor()
	assert.deepEqual((await (await student.request.get('/api/library')).json()).boards, [])
	report.checks.push('onboarding to empty, private class library')
	await page.getByRole('button', { name: 'Cuenta de Prueba temporal', exact: true }).click()
	await page.getByRole('menuitem', { name: 'Mi perfil', exact: true }).click()
	await verifyProfileControls(page)
	await verifyInlinePassEditor(page)
	await verifyProfileRefinements(page)
	report.checks.push('left-aligned compact card, Save visible at seven sizes, right-only carousel, unclipped drag and flip, stationary panel fades, per-cover sticker persistence')
	report.checks.push('card size and controls, complete border, tilt reset, pointer and keyboard menu animation, reduced motion')
	report.checks.push('inline carousel continuity, drag and keyboard, sticker placement, cancel, failed-save recovery, responsive layout and interrupted flip controls')
	const download = page.waitForEvent('download')
	await page.getByRole('button', { name: 'Descargar imagen', exact: true }).click()
	const file = await download
	assert.equal(await file.failure(), null)
	const png = await readFile(await file.path())
	assert.deepEqual([...png.subarray(0, 8)], [137, 80, 78, 71, 13, 10, 26, 10])
	assert.equal(png.readUInt32BE(16), 1200)
	report.checks.push('profile PNG download: 1200px wide')
	await page.getByRole('button', { name: 'Personalizar mi pase', exact: true }).click()
	await selectProfileSkin(page, 'halo')
	await page.getByRole('button', { name: 'Arrastrar Estrella', exact: true }).press('Enter')
	for (const width of [1024, 850, 390, 320]) {
		await page.setViewportSize({ width, height: 850 })
		assert(await page.locator('main').evaluate((el) => el.scrollWidth <= el.clientWidth + 1), `Horizontal overflow at ${width}px`)
	}
	await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
	await page.locator('.portal-profile[data-editing="false"]').waitFor()
	const profile = await (await student.request.get('/api/portal/pass')).json()
	assert.equal(profile.draft.skin, 'halo'); assert.equal(profile.draft.stickers.length, 1)
	await page.reload()
	await page.getByRole('heading', { name: 'Mi perfil', exact: true }).waitFor()
	assert.equal(await page.locator('.profile-card-stage .pass-carousel-card[data-selected="true"] .pass-sticker').count(), 1)
	report.checks.push('skin/sticker persistence and 320–1024px layout')
	assert.equal(await page.getByLabel('Contraseña actual', { exact: true }).count(), 0)
	await page.getByRole('button', { name: 'Cambiar contraseña', exact: true }).click()
	await page.getByLabel('Contraseña actual', { exact: true }).fill(password)
	await page.getByLabel('Nueva contraseña', { exact: true }).fill(nextPassword)
	await page.getByLabel('Repite la contraseña', { exact: true }).fill(nextPassword)
	await page.getByRole('button', { name: 'Actualizar contraseña', exact: true }).click()
	await page.getByText('Contraseña actualizada. Tus otras sesiones se cerraron.', { exact: true }).waitFor()
	report.checks.push('password change in production')
	await expected(await teacher.request.put(`/api/portal/boards/${report.boardId}/access`, { data: { grants: [{ kind: 'user', subjectId: report.studentId }] } }), 200)
	const library = await (await student.request.get('/api/library')).json()
	assert.deepEqual(library.boards.map((b) => b.id), [report.boardId])
	await expected(await student.request.get('/api/boards/principal'), 404)
	await page.setViewportSize({ width: 1024, height: 768 })
	await page.goto(`/board/${report.boardId}`)
	await page.locator('.tl-container').waitFor()
	assert.equal(await page.getByRole('button', { name: 'Recursos', exact: true }).count(), 0)
	assert.equal(await page.getByTestId('canvas-grid-toggle').count(), 0)
	await page.getByTestId('tools.hand').waitFor()
	assert.deepEqual(await page.locator('.tlui-main-toolbar [data-testid^="tools."]').evaluateAll((buttons) => buttons.map((button) => button.dataset.testid)), ['tools.hand'])
	for (const name of ['Compartir', 'Guardar copia', 'Salir', 'Salir de edición']) assert.equal(await page.getByRole('button', { name, exact: true }).count(), 0)
	const zoomButton = page.getByTestId('minimap.zoom-menu-button')
	const zoomBefore = await zoomButton.getAttribute('aria-label')
	await page.mouse.move(600, 400); await page.mouse.wheel(0, -120)
	await page.waitForFunction((label) => document.querySelector('[data-testid="minimap.zoom-menu-button"]')?.getAttribute('aria-label') !== label, zoomBefore)
	for (const key of ['v', 'l', 'Escape']) await page.keyboard.press(key)
	assert.equal(await page.getByTestId('tools.hand').getAttribute('aria-pressed'), 'true')
	report.checks.push('hand-only viewer controls, no grid or duplicate buttons, wheel zoom and keyboard restrictions')
	await expected(await student.request.post('/api/boards', { data: { name: 'not allowed' } }), 403)
	await expected(await student.request.get(`/api/boards/${report.boardId}/export`), 404)
	assert.equal(await page.locator('.tl-watermark').count(), 0)
	assert.deepEqual(licenseErrors, [])
	report.checks.push('licensed tldraw canvas, granted-only library and read-only student')
	await expected(await teacher.request.put(`/api/portal/boards/${report.boardId}/access`, { data: { grants: [] } }), 200)
	await page.getByRole('heading', { name: 'No pude abrir este canvas', exact: true }).waitFor()
	await expected(await student.request.get(`/api/boards/${report.boardId}`), 404)
	report.checks.push('live WebSocket access revocation')
	assert.deepEqual(errors, [])
	report.success = true
} finally {
	if (report.boardId) {
		report.cleanup.grantsCleared = (await teacher.request.put(`/api/portal/boards/${report.boardId}/access`, { data: { grants: [] } })).ok()
		report.cleanup.testBoardTrashed = (await teacher.request.patch(`/api/boards/${report.boardId}`, { data: { trashed: true } })).ok()
	}
	if (report.studentId) report.cleanup.testAccountDisabled = (await teacher.request.patch(`/api/portal/students/${report.studentId}`, { data: { disabled: true } })).ok()
	await teacher.request.post('/api/portal/logout')
	report.finishedAt = new Date().toISOString()
	await saveReport()
	await browser.close()
	console.log(JSON.stringify({ success: report.success ?? false, checks: report.checks, cleanup: report.cleanup }, null, 2))
}
